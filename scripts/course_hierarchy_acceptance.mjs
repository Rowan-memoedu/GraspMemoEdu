import fs from 'node:fs/promises';
import path from 'node:path';
import os from 'node:os';
import assert from 'node:assert/strict';
import {createRequire} from 'node:module';

const root = process.argv[2];
assert.ok(root?.replaceAll('\\', '/').startsWith('D:/Artifacts/GraspMemoEdu/'));
const base = process.argv[3] || 'http://127.0.0.1:18849';
assert.match(base, /^http:\/\/127\.0\.0\.1:\d+$/);
const identities = JSON.parse(await fs.readFile(root + '/fixture/identity.private.json', 'utf8'));
const require = createRequire(path.join(os.homedir(), '.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/_entry.cjs'));
const {chromium} = require('playwright');
const browser = await chromium.launch({headless: true, executablePath: path.join(os.homedir(), 'AppData/Local/Google/Chrome/Application/chrome.exe')});
const checks = [], errors = [];
const pass = label => { checks.push(label); console.log('PASS ' + label); };
async function login(label) {
  const context = await browser.newContext({viewport: {width: 1365, height: 960}, locale: 'zh-CN'});
  const page = await context.newPage(); page.setDefaultTimeout(30000);
  page.on('pageerror', e => errors.push(e.message));
  await page.goto(base + '/#/', {waitUntil: 'networkidle'});
  await page.locator('#userMenuButton').click(); await page.locator('#identityButton').click();
  await page.locator('#invitationCode').fill(identities[label].invitation_code);
  await page.locator('#identitySubmitButton').click(); await page.locator('#identityDialog').waitFor({state: 'hidden'});
  await page.goto(base + '/#/subjects/math/learn', {waitUntil: 'networkidle'});
  await page.locator('.incompleteTasks').waitFor();
  return page;
}
try {
  const page = await login('advanced');
  assert.equal(await page.locator('.courseUnitGroup').count(), 4);
  assert.equal(await page.locator('[data-unit-id="done-only"], [data-unit-id="empty"]').count(), 0);
  const first = page.locator('.incompleteTasks > .portalTask').first();
  assert.equal(await first.locator('.reviewMastery i').count(), 4);
  assert.equal(await first.locator('.reviewMastery i.filled').count(), 1);
  const barBottoms = await first.locator('.reviewMastery i').evaluateAll(bars => bars.map(bar => bar.getBoundingClientRect().bottom));
  assert.ok(Math.max(...barBottoms) - Math.min(...barBottoms) < 1);
  assert.equal(await page.locator('.courseUnitGroup .reviewMastery').count(), 0);
  pass('Advanced view groups uneven branches, hides finished/empty branches, and puts review with low mastery icon first');
  await page.locator('[data-unit-id="b"] > summary').click();
  await page.locator('[data-unit-id="c"] > summary').click();
  await page.locator('[data-unit-id="d"] > summary').click();
  await page.locator('[data-task-id="lesson:blocked"] .taskToggle').click();
  assert.equal(await page.locator('[data-task-id="lesson:blocked"] .prerequisiteBlocked').isDisabled(), true);
  await page.locator('[data-task-id="lesson:paused"] .taskToggle').click();
  await page.locator('[data-task-id="lesson:paused"] .taskStatusNote').waitFor();
  await page.screenshot({path: root + '/hierarchy-desktop.png', fullPage: true});
  pass('Nested accordion preserves blocked and paused Topic interactions');
  await page.setViewportSize({width: 390, height: 844});
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
  await page.screenshot({path: root + '/hierarchy-mobile.png', fullPage: true});
  pass('Mobile layout has no horizontal overflow');
  await page.setViewportSize({width: 1365, height: 960});
  await page.locator('[data-task-id="lesson:ready"] .taskToggle').click();
  await page.locator('[data-task-id="lesson:ready"] .taskStartRow button').first().click();
  await page.locator('#stepCard').waitFor();
  assert.ok(page.url().includes('/topic/ready'));
  pass('Original Topic entry opens the original learning view');
  await page.goto(base + '/#/settings', {waitUntil: 'networkidle'});
  await page.locator('#courseHierarchyEnabled').waitFor();
  assert.equal(await page.locator('#courseHierarchyEnabled').isChecked(), true);
  await page.locator('#courseHierarchyEnabled').uncheck();
  await page.locator('.profileForm button[type="submit"]').click();
  await page.getByText('设置已保存', {exact: false}).waitFor();
  await page.goto(base + '/#/subjects/math/learn', {waitUntil: 'networkidle'});
  await page.locator('.incompleteTasks').waitFor();
  assert.equal(await page.locator('.courseUnitGroup').count(), 0);
  await page.reload({waitUntil: 'networkidle'});
  assert.equal(await page.locator('.courseUnitGroup').count(), 0);
  pass('Settings disable hierarchy and survive reload');
  const device = await login('advanced');
  assert.equal(await device.locator('.courseUnitGroup').count(), 0);
  pass('A new browser session reads the same saved preference');
  const standard = await login('standard');
  assert.equal(await standard.locator('.courseUnitGroup').count(), 0);
  assert.equal(await standard.locator('.reviewMastery i.filled').count(), 1);
  await standard.goto(base + '/#/settings', {waitUntil: 'networkidle'});
  assert.equal(await standard.locator('#courseHierarchyEnabled').count(), 0);
  pass('Standard learner stays flat, has the review icon, and cannot see the advanced setting');
  assert.deepEqual(errors, []);
} finally {
  await fs.writeFile(root + '/browser-report.json', JSON.stringify({checks, errors}, null, 2));
  await browser.close();
}
