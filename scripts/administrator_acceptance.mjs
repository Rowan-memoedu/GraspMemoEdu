import fs from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';
import assert from 'node:assert/strict';
import {createRequire} from 'node:module';
const [base, privateFile, out] = process.argv.slice(2);
assert.equal(new URL(base).hostname, '127.0.0.1');
await fs.mkdir(out, {recursive: true});
const accounts = JSON.parse(await fs.readFile(privateFile, 'utf8')).accounts;
const require = createRequire(path.join(os.homedir(), '.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/_entry.cjs'));
const {chromium} = require('playwright');
const browser = await chromium.launch({headless: true, executablePath: path.join(os.homedir(), 'AppData/Local/Google/Chrome/Application/chrome.exe')});
const page = await browser.newPage({viewport: {width: 1365, height: 960}, locale: 'zh-CN'});
page.setDefaultTimeout(30000);
const errors = [], checks = [];
page.on('pageerror', e => errors.push(e.message));
const pass = text => { checks.push(text); console.log('PASS ' + text); };
const go = route => page.goto(base + '/#' + route, {waitUntil: 'networkidle'});
try {
  await go('/subjects/english/reviews');
  await page.locator('#userMenuButton').click(); await page.locator('#identityButton').click();
  await page.locator('#invitationCode').fill(accounts[0].invitation_code);
  await page.locator('#identitySubmitButton').click();
  await page.locator('#identityDialog').waitFor({state: 'hidden'});
  await page.getByRole('link', {name: '进入卡片', exact: true}).first().waitFor();
  assert.equal(await page.getByRole('link', {name: '进入卡片', exact: true}).count(), 7);
  await page.screenshot({path: path.join(out, 'all-cards.png'), fullPage: true});
  pass('All seven unlearned cards, variants and bundle available');
  await go('/subjects/english/review/atoms/atomic?card=c-1');
  await page.locator('#atomicAnswer').fill('圆形');
  await page.locator('#atomicAnswer').press('Control+Enter');
  await page.locator('.atomicMain .feedback.correct').waitFor({timeout: 120000});
  await page.locator('.atomicMain').getByRole('button', {name: '继续', exact: true}).click();
  await page.locator('.atomicComplete').waitFor();
  pass('Single card uses real semantic judge and completes without further push');
  await go('/subjects/english/review/atoms/atomic?card=ab-bundle');
  await page.locator('[data-blank-id=a]').fill('红色');
  await page.locator('[data-blank-id=b]').fill('蓝色');
  await page.locator('[data-blank-id=b]').press('Control+Enter');
  await page.locator('.atomicMain .feedback.correct').waitFor();
  pass('Bundled card preserves normal fill-blank interaction');
  await go('/subjects/math/topic/after');
  await page.locator('#stepCard').getByRole('button', {name: '已掌握，试着作答', exact: true}).click();
  await page.locator('#answerInput').fill('5'); await page.locator('#submitButton').click();
  await page.locator('#stepCard .feedback.correct').waitFor({timeout: 120000});
  pass('Prerequisite bypass and normal Lesson choice, answer, real judgement');
  const persisted = await page.evaluate(() => [localStorage, sessionStorage].flatMap(storage => Object.keys(storage).filter(key => /(^|:)(draft|elapsed|submission)(:|$)/.test(key))));
  assert.deepEqual(persisted, []);
  assert.deepEqual(errors, []);
  await page.screenshot({path: path.join(out, 'normal-lesson.png'), fullPage: true});
  pass('No learning drafts, timers or submissions in Web Storage; no browser errors');
} finally {
  await fs.writeFile(path.join(out, 'report.json'), JSON.stringify({checks, errors}, null, 2));
  await browser.close();
}
